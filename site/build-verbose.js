#!/usr/bin/env node
/**
 * build-verbose.js — Full build including lesson content embedding
 * Runs after site/build.js to generate lessons-content.js with all
 * lesson markdown (English + Chinese) embedded as static JS.
 *
 * This makes lesson.html work without any network requests on Vercel static.
 */

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..');
const PHASES_DIR = path.join(REPO_ROOT, 'phases');
const OUTPUT = path.join(__dirname, 'lessons-content.js');

// ─── Markdown renderer (same minimal parser as local server) ─────────
function parseMd(text) {
  if (!text) return '';
  text = text
    .replace(/```(\w*)\n([\s\S]*?)```/g, (_, lang, code) =>
      `<pre><code class="lang-${lang}">${escapeHtml(code.trim())}</code></pre>`)
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/^### (.+)$/gm, '<h3>$1</h3>')
    .replace(/^## (.+)$/gm, '<h2>$1</h2>')
    .replace(/^# (.+)$/gm, '<h1>$1</h1>')
    .replace(/\*\*\*(.+?)\*\*\*/g, '<strong><em>$1</em></strong>')
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/\*(.+?)\*/g, '<em>$1</em>')
    .replace(/^> (.+)$/gm, '<blockquote>$1</blockquote>')
    .replace(/^---$/gm, '<hr>')
    .replace(/^- (.+)$/gm, '<li>$1</li>')
    .replace(/^\d+\. (.+)$/gm, '<li>$1</li>')
    .replace(/\|(.+)\|/g, (match) => {
      const cells = match.split('|').filter(c => c.trim());
      if (cells.some(c => /^-+$/.test(c.trim()))) return '';
      return '<tr>' + cells.map(c => `<td>${c.trim()}</td>`).join('') + '</tr>';
    })
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>')
    .replace(/\n\n+/g, '</p><p>')
    .replace(/\n/g, '<br>');
  text = text.replace(/(<li>.*<\/li>)+/gs, '<ul>$&</ul>');
  text = text.replace(/(<tr>.*<\/tr>)+/gs, '<table>$&</table>');
  text = text.replace(/<p><\/p>/g, '');
  return '<p>' + text + '</p>';
}

function escapeHtml(str) {
  return String(str).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

// ─── Load quiz.json if exists ─────────────────────────────────────────
function loadQuiz(lessonPath) {
  const quizPath = path.join(REPO_ROOT, lessonPath, 'quiz.json');
  try {
    return JSON.parse(fs.readFileSync(quizPath, 'utf8'));
  } catch (_) { return null; }
}

// ─── Load outputs directory listing ───────────────────────────────────
function loadOutputs(lessonPath) {
  const outputsDir = path.join(REPO_ROOT, lessonPath, 'outputs');
  try {
    const entries = fs.readdirSync(outputsDir, { withFileTypes: true });
    return entries.filter(e => e.isFile()).map(e => e.name);
  } catch (_) { return []; }
}

// ─── Collect all lessons ───────────────────────────────────────────────
function collectLessons() {
  const lessons = {};
  const phaseDirs = fs.readdirSync(PHASES_DIR, { withFileTypes: true });
  for (const phaseEntry of phaseDirs) {
    if (!phaseEntry.isDirectory()) continue;
    const phasePath = path.join(PHASES_DIR, phaseEntry.name);
    try {
      const lessonDirs = fs.readdirSync(phasePath, { withFileTypes: true });
      for (const lessonEntry of lessonDirs) {
        if (!lessonEntry.isDirectory()) continue;
        const lessonRel = `phases/${phaseEntry.name}/${lessonEntry.name}`;
        const docsDir = path.join(phasePath, lessonEntry.name, 'docs');
        const enPath = path.join(docsDir, 'en.md');
        const zhPath = path.join(docsDir, 'zh.md');

        const enMd = fs.existsSync(enPath) ? fs.readFileSync(enPath, 'utf8') : '';
        const zhMd = fs.existsSync(zhPath) ? fs.readFileSync(zhPath, 'utf8') : null;
        const quiz = loadQuiz(lessonRel);
        const outputs = loadOutputs(lessonRel);

        lessons[lessonRel] = {
          en: enMd,
          zh: zhMd || null,
          quiz: quiz,
          outputs: outputs,
        };
      }
    } catch (_) {}
  }
  return lessons;
}

// ─── Main ──────────────────────────────────────────────────────────────
console.log('📚 Loading all lesson content...');
const lessons = collectLessons();
const lessonKeys = Object.keys(lessons);
console.log(`   Found ${lessonKeys.length} lessons`);

// Write as JS module (not JSON — allows lazy loading)
const js = `// Auto-generated by build-verbose.js — do not edit manually.
// Built: ${new Date().toISOString()}
// Languages: en, zh (embedded)

const LESSONS_CONTENT = ${JSON.stringify(lessons, null, 2)};
const LESSONS_LANG = 'en';
const LESSONS_AVAILABLE = Object.keys(LESSONS_CONTENT);
`;
fs.writeFileSync(OUTPUT, js, 'utf8');
console.log(`\n✅ Generated ${OUTPUT} (${lessonKeys.length} lessons, ~${(fs.statSync(OUTPUT).size / 1024 / 1024).toFixed(1)} MB)`);